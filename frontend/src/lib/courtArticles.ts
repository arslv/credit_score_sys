/** Номер статьи из строки бюро: «ст. 12.2 ч. 4» → «12.2». */
export function articleNumber(text: string): string | null {
  return /(\d+(?:\.\d+)*)/.exec(text)?.[1] ?? null;
}

/**
 * Суть статьи. code — «КоАП» (административные дела) или «УК» (уголовные).
 * Неизвестная статья КоАП — по главе; неизвестная статья УК — null.
 */
export function explainArticle(text: string, code: "КоАП" | "УК"): Article | null {
  const num = articleNumber(text);
  if (!num) return null;
  if (code === "УК") return UK[num] ?? null;
  return KOAP[num] ?? KOAP_CHAPTER[num.split(".")[0]] ?? null;
}
